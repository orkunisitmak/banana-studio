import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { auditDistribution } from './audit-distribution.mjs';
import { copyRuntimePackages } from './copy-runtime-packages.mjs';

const root=path.resolve(import.meta.dirname,'..');
if(process.platform!=='linux'||process.arch!=='x64')throw new Error('Package and test on glibc Linux x64.');
const version=JSON.parse(fs.readFileSync(path.join(root,'package.json'))).version;
const runtime=path.join(root,'.build/node-runtime');
const lock=JSON.parse(fs.readFileSync(path.join(root,'desktop/node-runtime.json'))).releases['linux-x64'];
const digest=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
if(digest(path.join(runtime,'bin/node'))!==lock.binarySha256||digest(path.join(runtime,'LICENSE'))!==lock.licenseSha256)throw new Error('The official Node runtime or license checksum does not match.');
const app=path.join(root,'.build/staging-linux/Banana Studio');
fs.rmSync(app,{recursive:true,force:true});fs.mkdirSync(path.join(app,'runtime'),{recursive:true});
fs.copyFileSync(path.join(runtime,'bin/node'),path.join(app,'runtime/node'));
fs.chmodSync(path.join(app,'runtime/node'),0o755);
fs.copyFileSync(path.join(runtime,'LICENSE'),path.join(app,'Node-LICENSE.txt'));
fs.copyFileSync(path.join(root,'desktop/linux/banana_studio.py'),path.join(app,'banana_studio.py'));
fs.copyFileSync(path.join(root,'public/icon-192.png'),path.join(app,'icon.png'));
fs.writeFileSync(path.join(app,'banana-studio'),'#!/bin/sh\nexec /usr/bin/python3 "$(dirname "$(readlink -f "$0")")/banana_studio.py" "$@"\n',{mode:0o755});
const workspace=path.join(app,'workspace');fs.mkdirSync(workspace,{recursive:true});
fs.copyFileSync(path.join(root,'.build/desktop/server.mjs'),path.join(workspace,'server.mjs'));
fs.writeFileSync(path.join(workspace,'package.json'),JSON.stringify({name:'banana-studio-local-runtime',private:true,type:'module'}));
fs.cpSync(path.join(root,'dist'),path.join(workspace,'web'),{recursive:true});
const copied=copyRuntimePackages('sharp',root,path.join(workspace,'node_modules'));
if(!copied.has('@img/sharp-linux-x64')||!copied.has('@img/sharp-libvips-linux-x64'))throw new Error('The glibc Linux image codec is missing.');
for(const [source,target] of [['LICENSE','LICENSE.txt'],['docs/THIRD_PARTY_NOTICES.md','THIRD_PARTY_NOTICES.md'],['desktop/linux/README.md','README.md']])fs.copyFileSync(path.join(root,source),path.join(app,target));
const sourceCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
fs.writeFileSync(path.join(app,'release.json'),JSON.stringify({version,sourceCommit,platform:'linux-x64',distribution:'unsigned-community',runtimePackages:Object.fromEntries(copied)},null,2));
const audit=auditDistribution(app);if(!audit.ok)throw new Error('Distribution audit rejected the Linux package: '+JSON.stringify(audit.findings));
const archive=path.join(root,`.build/Banana-Studio-${version}-linux-x64.tar.gz`);
execFileSync('tar',['-czf',archive,'-C',path.dirname(app),path.basename(app)]);
fs.writeFileSync(path.join(root,'.build/verification-linux-x64.json'),JSON.stringify({version,sourceCommit,platform:'linux-x64',sha256:digest(archive),distribution:'unsigned-community',nativeUiVerification:'not-performed-by-packager'},null,2));
console.log(JSON.stringify({app,archive,version,sourceCommit,files:audit.files}));
